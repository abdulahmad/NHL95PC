#!/usr/bin/env python3
"""gen_src.py - (re)generate the committed NASM source tree src/ from HOCKEY.EXE (maintainer tool).

  python3 tools/gen_src.py [--no-listing]

Uses the same emitter as tools/asm_proto.py: every segment of segmap95pc.json (code, initialised data and BSS)
becomes src/<object>/<NNN>_<ADDR>_<module>.asm, one NASM section s_<ADDR> per file, with symbolic labels for
every fixup target / branch target / function entry, names from name_map_94.csv + tools/global_map.csv, and
per-element fallbacks (LD macro, db) wherever nasm would pick a different encoding. Each file is assembled and
checked against the EXE (bytes + fixup set) before it is written to src/.
Also writes
  src/segments.txt      the layout list read by tools/link_src.py (and the Makefile / build.sh)
  src/inc/symbols.inc   cross-segment symbol table (comments): every label referenced from another file
Needs build/parts (rebuild_exe.py extract), iced-x86, nasm; names come from the listing caches unless --no-listing.
Output is deterministic: the same inputs give byte-identical files. Regenerating overwrites hand edits in src/."""
import os, sys, json, re, argparse, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fixup_labels as FL, asm_proto as AP
ROOT = FL.ROOT; SRC = os.path.join(ROOT, 'src')
OBJDIR = {1: 'cseg01', 2: 'dseg02'}
HDR = '; %s %05X-%05X  NHL 95 PC HOCKEY.EXE %s; generated by tools/gen_src.py, assembled by `make` (see docs/ASM_BUILD.md)'

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--no-listing', action='store_true'); a = ap.parse_args()
    A = FL.analyse(use_listing=not a.no_listing)
    os.makedirs(AP.OUT, exist_ok=True)
    rows = []; written = set(); defined = {}; used = {}
    for seg in A.segs:
        s0, s1, mod, ob = seg
        idx = AP.seg_index(A, seg)
        r, buf, fx = AP.build_segment(A, seg, idx)
        if not (r['bytes_match'] and r['fixups_match']): sys.exit('segment %05X %s does not round-trip: %s' % (s0, mod, json.dumps(r)))
        name = '%03d_%05X_%s.asm' % (idx, s0, mod)
        text = open(os.path.join(AP.OUT, name)).read().split('\n')
        assert text[0] == AP.HEADER % (mod, s0, s1)
        text[0] = HDR % (mod, s0, s1, OBJDIR[ob])
        rel = '%s/%s' % (OBJDIR[ob], name)
        os.makedirs(os.path.join(SRC, OBJDIR[ob]), exist_ok=True)
        open(os.path.join(SRC, rel), 'w').write('\n'.join(text))
        written.add(rel)
        rows.append('%d %05X %05X %d %s %s' % (ob, s0, s1, r['file_bytes'], mod, rel))
        for ln in text:
            if ln.startswith('global '):
                for n in ln[7:].split(', '): defined[n] = rel
            elif ln.startswith('extern '):
                for n in ln[7:].split(', '): used.setdefault(n, set()).add(rel)
        print('%-48s %s' % (rel, 'ok'), flush=True)
    for ob in OBJDIR.values():     # drop files of segments that no longer exist
        for f in sorted(os.listdir(os.path.join(SRC, ob))):
            if f.endswith('.asm') and '%s/%s' % (ob, f) not in written: os.remove(os.path.join(SRC, ob, f))
    with open(os.path.join(SRC, 'segments.txt'), 'w') as fo:
        fo.write('# NHL 95 PC HOCKEY.EXE segment layout (generated by tools/gen_src.py from segmap95pc.json)\n'
                 '# Linked in this order by tools/link_src.py; the section s_<start> of each file is placed at <start>.\n'
                 '# object start end initialised_bytes module source (relative to src/)\n')
        fo.write('\n'.join(rows) + '\n')
    lab = AP.Names(A)
    rev = {}
    for a_ in set(A.tgt.values()) | set(A.fentry) | set(A.names) | set(A.branch_targets):
        rev[lab(a_)] = a_
    with open(os.path.join(SRC, 'inc/symbols.inc'), 'w') as fo:
        fo.write('; Cross-segment symbols of NHL 95 PC HOCKEY.EXE (generated by tools/gen_src.py; reference only).\n'
                 '; Every label that one src/ file references in another: address, name, defining file, number of users.\n'
                 '; The files declare their own global/extern lists; tools/link_src.py resolves them by name.\n')
        for n in sorted(used, key=lambda n: (rev.get(n, 0), n)):
            fo.write(';  %05X  %-40s %-44s %d\n' % (rev.get(n, 0), n, defined.get(n, '?'), len(used[n])))
    missing = sorted(n for n in used if n not in defined)
    print('segments', len(rows), 'cross-segment symbols', len(used), 'undefined', missing[:20])

if __name__ == '__main__':
    main()
