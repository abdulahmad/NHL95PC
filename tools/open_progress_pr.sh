#!/bin/bash
# Open or update the progress PR from a tree where tools/round_bookkeeping.py and
# make fullcheck have already run. Exits 0 when the regenerated tree matches main.
# Never force-pushes. Uses PROGRESS_TOKEN for the push and for gh when it is set,
# because GITHUB_TOKEN does not start pull_request workflows.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ "${GITHUB_ACTIONS:-}" != "true" ]; then
  echo "tools/open_progress_pr.sh is run by .github/workflows/progress.yml" >&2
  exit 1
fi

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"

PATHS=(
  C_PROGRESS.md
  tools/c_functions.csv
  README.md
  HANDOFF.md
  docs/ranked_drafts.txt
  docs/LANES_CURRENT.md
  docs/pending_renames.txt
  docs/draft_history.csv
)

BR=progress/bookkeeping
MAIN_SHA=$(git rev-parse HEAD)

git add -A -- "${PATHS[@]}" src tools
if git diff --cached --quiet; then
  echo "progress files already match ${MAIN_SHA}; not opening a PR"
  exit 0
fi

git checkout -B progress/bookkeeping-tree
git commit -m "Progress: regenerate counts, lanes and renames"
NEW=$(git rev-parse HEAD)

if [ -n "${PROGRESS_TOKEN:-}" ]; then
  # The checkout action's extraheader authenticates as GITHUB_TOKEN and wins over
  # a token embedded in the remote URL. Drop it so this push starts fullcheck.
  git config --unset-all http.https://github.com/.extraheader || true
  git remote set-url origin "https://x-access-token:${PROGRESS_TOKEN}@github.com/${GITHUB_REPOSITORY}.git"
  export GH_TOKEN="${PROGRESS_TOKEN}"
else
  export GH_TOKEN="${GITHUB_TOKEN:?GITHUB_TOKEN is not set}"
fi

git fetch origin "${BR}" || true

open=0
if git show-ref --verify --quiet "refs/remotes/origin/${BR}"; then
  n=$(gh pr list --head "${BR}" --base main --state open --json number --jq 'length')
  if [ "${n}" = "0" ]; then
    if ! git push origin --delete "${BR}"; then
      echo "could not delete ${BR} (the ruleset blocks deletion); using a new branch"
      BR="progress/bookkeeping-${GITHUB_RUN_ID}"
    else
      git fetch origin --prune || true
    fi
  else
    open=1
  fi
fi

if [ "${open}" = "1" ]; then
  git checkout -B "${BR}" "origin/${BR}"
  # On a conflict, continue from main's tree. The regenerated commit is the one
  # fullcheck just passed, and it is checked out over the progress files below.
  if ! git merge "${MAIN_SHA}" -m "Merge main into the progress branch"; then
    git checkout --theirs -- .
    git add -A
    git commit -m "Merge main into the progress branch"
  fi
  if ! git merge "${NEW}" -m "Merge regenerated progress"; then
    git checkout "${NEW}" -- "${PATHS[@]}"
    git add -A -- "${PATHS[@]}" src tools
    git commit -m "Progress: regenerate counts, lanes and renames"
  fi
  if ! git diff --quiet "${NEW}" -- "${PATHS[@]}"; then
    git checkout "${NEW}" -- "${PATHS[@]}"
    git add -A -- "${PATHS[@]}"
    git commit -m "Progress: regenerate counts, lanes and renames"
  fi
else
  git checkout -B "${BR}" "${NEW}"
fi

if git diff --quiet "${MAIN_SHA}"; then
  echo "progress tree matches main; not opening a PR"
  exit 0
fi

if git show-ref --verify --quiet "refs/remotes/origin/${BR}" && git diff --quiet "origin/${BR}"; then
  echo "origin/${BR} already has this tree"
else
  git push -u origin "${BR}"
fi

cat > /tmp/progress-pr-body.md <<'EOF'
Generated by the progress workflow after fullcheck on main.

It regenerated C_PROGRESS.md, tools/c_functions.csv, the README and HANDOFF counts between the nhl95 marker comments, docs/ranked_drafts.txt and docs/LANES_CURRENT.md, and applied docs/pending_renames.txt when it had rename lines.

`make fullcheck` passed in this workflow before the PR was opened.
EOF

if [ -z "$(gh pr list --head "${BR}" --base main --state open --json number --jq '.[0].number // empty')" ]; then
  gh pr create --base main --head "${BR}" \
    --title "Progress: regenerate counts, lanes and renames" \
    --body-file /tmp/progress-pr-body.md
fi

if [ -z "${PROGRESS_TOKEN:-}" ]; then
  echo "::warning::PROGRESS_TOKEN is not set. This branch was pushed with GITHUB_TOKEN, which does not start the fullcheck workflow, so the required check never appears and auto-merge cannot complete. Add the PROGRESS_TOKEN secret (see the PR that added this workflow)."
  exit 0
fi

gh pr merge --auto --merge "${BR}" || echo "::warning::could not enable auto-merge. Allow auto-merge is off, or the ruleset asked for an extra approval."
