#!/usr/bin/env python3
"""update_symbols.py - regenerate src/inc/symbols.inc from the src/ tree (after `make`).

  python3 tools/update_symbols.py [--obj build/obj] [--check]

src/inc/symbols.inc is the shared symbol index of the source tree (the PC analogue of the Genesis repos'
ram_addrs.inc): every label that one src/ file uses from another, with its address, its defining file and the number
of files that use it. Definitions stay in their segment file (data and BSS names in src/dseg02/*.asm, code names in
src/cseg01/*.asm); this file is only the index, so it never needs hand edits. Addresses come from the objects that
`make` wrote to build/obj (section s_<ADDR> + symbol value), names from the global/extern lists of the .asm files.
--check: exit 1 if the file on disk is not what would be written (e.g. after a hand rename)."""
import os, re, sys, argparse
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from link_src import read_elf, read_layout
SRC = os.path.join(ROOT, 'src'); INC = os.path.join(SRC, 'inc/symbols.inc')
HEAD = ('; Cross-segment symbols of NHL 95 PC HOCKEY.EXE (generated by tools/update_symbols.py; do not edit).\n'
        '; Every label that one src/ file references in another: address, name, defining file, number of users.\n'
        '; The files declare their own global/extern lists; tools/link_src.py resolves them by name.\n')

def decl_lists(text):
    """(globals, externs) of one .asm file"""
    g, e = [], []
    for ln in text.split('\n'):
        if ln.startswith('global '): g += [n.strip() for n in ln[7:].split(';')[0].split(',') if n.strip()]
        elif ln.startswith('extern '): e += [n.strip() for n in ln[7:].split(';')[0].split(',') if n.strip()]
    return g, e

def addresses(objdir, segs):
    addr = {}
    for sg in segs:
        d, secs, syms, rels = read_elf(os.path.join(objdir, os.path.splitext(sg['src'])[0] + '.o'))
        si = next(i for i, s in enumerate(secs) if s['name'] == 's_%05X' % sg['start'])
        for sy in syms:
            if sy['bind'] == 1 and sy['shndx'] == si: addr[sy['name']] = sg['start'] + sy['value']
    return addr

def render(objdir):
    segs = read_layout()
    defined, used = {}, {}
    for sg in segs:
        g, e = decl_lists(open(os.path.join(SRC, sg['src'])).read())
        for n in g: defined[n] = sg['src']
        for n in e: used.setdefault(n, set()).add(sg['src'])
    addr = addresses(objdir, segs)
    out = [HEAD]
    for n in sorted(used, key=lambda n: (addr.get(n, 0), n)):
        out.append(';  %05X  %-40s %-44s %d\n' % (addr.get(n, 0), n, defined.get(n, '?'), len(used[n])))
    return ''.join(out)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--obj', default=os.path.join(ROOT, 'build/obj')); ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    new = render(a.obj)
    old = open(INC).read() if os.path.exists(INC) else ''
    if a.check:
        print('symbols.inc up to date' if new == old else 'symbols.inc is stale: run tools/update_symbols.py'); sys.exit(0 if new == old else 1)
    if new != old: open(INC, 'w').write(new)
    print('wrote src/inc/symbols.inc (%d symbols)%s' % (new.count('\n') - 3, '' if new != old else ', unchanged'))

if __name__ == '__main__':
    main()
