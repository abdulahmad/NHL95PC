#!/usr/bin/env python3
"""work_queue.py - write docs/WORK_QUEUE.md, the queue of C drafts that do not match yet.

  python3 tools/work_queue.py [--history docs/draft_history.csv] [--ranked docs/ranked_drafts.txt]

One owner, no lanes (the lane rounds are in docs/archive/). Every nonmatching draft in tools/c_functions.csv is
listed by C file, closest first. A draft with two consecutive no-gain attempts under GA is parked: it moves to
the Parked list with its history, unless a tool for its cause landed after the last attempt (then it stays in
the queue with that tool named). The result is a pure function of the history, the cause column and the tool
dates, so running it again on the same tree rewrites the same file.
"""
import argparse, csv, os, subprocess
from collections import defaultdict
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'docs/WORK_QUEUE.md')

# cause word -> tools that can move a draft of that cause. The date is the commit that added the file.
TOOLS = [
    ('tools/wccre/regdump.py', 'register', 'regdump'),
    ('tools/wccre/regsolve.py', 'register', 'regsolve'),
    ('tools/wccre/declsearch.py', 'slot', 'declsearch'),
    ('tools/wccre/slotdump.py', 'slot', 'slotdump'),
]


def tool_added(path):
    if not os.path.exists(os.path.join(ROOT, path)):
        return None
    out = subprocess.check_output(['git', 'log', '--diff-filter=A', '--format=%cI', '--', path], cwd=ROOT, text=True)
    lines = [x for x in out.splitlines() if x]
    return lines[-1] if lines else None


def load_ranked(path):
    scores = {}
    if os.path.exists(path):
        for ln in open(path):
            parts = ln.split()
            if len(parts) >= 4:
                try:
                    scores[(parts[2], parts[3])] = (int(parts[0]), int(parts[1]))
                except ValueError:
                    pass
    return scores


def ga_rows(history, func):
    return [r for r in history if r['function'] == func and (r.get('compiler') or 'GA') == 'GA'
            and 'not reached' not in (r.get('shapes_tried') or '').lower()]


def streak(rows):
    n = 0
    for r in rows:
        before, after = int(r['score_before']), int(r['score_after'])
        n = n + 1 if (after >= before and after != 0) else 0
    return n


def new_tool(cause, rows, added):
    if not rows:
        return None
    last = max(r['date'] for r in rows)
    tried = ' '.join(r.get('shapes_tried') or '' for r in rows).lower()
    for path, applies, name in TOOLS:
        when = added.get(path)
        if applies == cause and when and when[:10] > last and name.lower() not in tried:
            return name
    return None


def history_lines(func, history):
    lines = []
    for r in history:
        if r['function'] == func:
            shape = (r.get('shapes_tried') or '').replace('**', '').replace('\n', ' ').strip()
            lines.append('- %s %s->%s (%s, %s) %s' % (r['function'], r['score_before'], r['score_after'], r['date'],
                                                      r.get('compiler') or 'GA', shape))
    return lines or ['- (no GA history rows)']


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--history', default=os.path.join(ROOT, 'docs/draft_history.csv'))
    ap.add_argument('--ranked', default=os.path.join(ROOT, 'docs/ranked_drafts.txt'))
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    os.chdir(ROOT)
    history = list(csv.DictReader(open(a.history, newline=''))) if os.path.exists(a.history) else []
    ranked = load_ranked(a.ranked)
    added = {path: tool_added(path) for path, _, _ in TOOLS}
    files = defaultdict(list)
    for r in csv.DictReader(open('tools/c_functions.csv', newline='')):
        if r['status'] != 'nonmatching':
            continue
        cause = r.get('cause') or ''
        rows = ga_rows(history, r['function'])
        parked = streak(rows) >= 2
        tool = new_tool(cause.split(' ')[0], rows, added) if parked else None
        files[r['c_file']].append(dict(function=r['function'], cause=cause, parked=parked and not tool, tool=tool,
                                       score=ranked.get((r['function'], r['c_file']), (9999,))[0]))
    for ds in files.values():
        ds.sort(key=lambda d: (d['score'], d['function']))
    order = sorted(files.items(), key=lambda kv: (min(d['score'] for d in kv[1]), kv[0]))
    queue = [(p, ds) for p, ds in order if not all(d['parked'] for d in ds)]
    parked = [(p, ds) for p, ds in order if all(d['parked'] for d in ds)]
    out = ['# Work queue', '',
           'Generated by `tools/work_queue.py` from `docs/draft_history.csv`, `tools/c_functions.csv` and '
           '`docs/ranked_drafts.txt`. Do not edit this file. Before each draft read its rows in the history and its '
           'entry in `docs/UNSURE.md`. One C file per unit; take the files from the top.', '',
           '## Queue', '', '| C file | Function | Score | Cause |', '|---|---|---:|---|']
    for path, ds in queue:
        for i, d in enumerate(ds):
            score = '' if d['score'] == 9999 else str(d['score'])
            cause = d['cause'] + (' (parked)' if d['parked'] else '') + (' (try `%s`)' % d['tool'] if d['tool'] else '')
            out.append('| %s | %s | %s | %s |' % (path if i == 0 else '', d['function'], score, cause))
    out += ['', '## Parked', '',
            'Two consecutive no-gain attempts under GA and no newer tool for the cause. Leave these until there is a '
            'new idea or a ruling in `docs/ESCALATIONS.md`.', '']
    if not parked:
        out += ['(none)', '']
    for path, ds in parked:
        out += ['### `%s`' % path, '']
        for d in ds:
            out.append('%s — %s' % (d['function'], d['cause'] or 'unscored'))
            out.extend(history_lines(d['function'], history))
        out.append('')
    open(a.out, 'w').write('\n'.join(out).rstrip() + '\n')
    print('%s: %d files in the queue, %d parked' % (os.path.relpath(a.out, ROOT), len(queue), len(parked)))


if __name__ == '__main__':
    main()
