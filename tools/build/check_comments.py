#!/usr/bin/env python3
"""check_comments.py - checks the comment rules in CONTRIBUTING.md ("Comments") on the .asm sources.

  python3 tools/build/check_comments.py [--summary] [--rule R[,R...]] [FILE...]   (default: every file under src/)

The same script runs in NHL95PC, NHL96PC and NHL97PC (it reads the layout from tools/build/format_asm.py).
Rules (the name in brackets is what --rule takes):
  [width]    no line that carries a comment is wider than 110 columns (data lines such as `db ...  ; insn:` aside)
  [column]   a comment after an instruction starts at column 48, or one space after code that reaches past it
  [para]     a paragraph of a routine header or block comment (split by a `;` line) has at most 3 lines
  [header]   every routine has a header between rule lines, with a description under the name line
  [data]     every data or BSS label (a variable, table or string) has a comment on its line
  [ida]      no IDA names in comments (sub_, loc_, unk_, dword_, byte_, word_, off_, qword_, asc_, jpt_, nullsub_)
  [lineage]  no other game's name in comments (94G, NHL 95, 96 PC ...): lineage lives in docs/name_map.csv;
             the SOURCE field on a header's name line is the one exception
  [file]     the file starts with a comment line that says what the file holds (not only the generator line)
--summary prints a count per rule and per folder instead of every line. Exit status 1 when anything is reported.
"""
import glob, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import asmaddr
import format_asm

WIDTH, COL, MAXPARA = 110, 48, 3
RULE = format_asm.RULE
LABEL = re.compile(r'^([A-Za-z_][\w$?@]*):(.*)$')
IDA = re.compile(r'\b(sub|loc|unk|dword|byte|word|off|qword|asc|jpt|nullsub|flt|dbl|stru|algn)_[0-9A-F]{4,}\b')
LINEAGE = re.compile(r'\b(9[2-7][GS]|NHLPA ?93|NHL ?9[2-7]|9[2-7] ?(PC|Genesis|SNES)|(Genesis|SNES|Sega)\b)', re.I)
DATA_OP = re.compile(r'^(db|dw|dd|dq|dt|resb|resw|resd|resq|rest|times|incbin|align|alignb)\b', re.I)
OWN = re.search(r'9(\d)', os.path.basename(asmaddr.ROOT)).group(0)   # this repo's own game is not lineage
RULES = 'width column para header data ida lineage file'.split()


def split(line):
    """(code, comment): the comment starts at the first ';' outside a string"""
    q = None
    for i, ch in enumerate(line):
        if q:
            if ch == q: q = None
        elif ch in "'\"`": q = ch
        elif ch == ';': return line[:i], line[i:]
    return line, None


def check(path):
    out = []
    L = open(path, encoding='latin1').read().split('\n')
    rel = os.path.relpath(path, asmaddr.SRC)
    starts = set()
    if not rel.startswith('data' + os.sep):
        try: starts = set(format_asm.routine_starts(L))
        except Exception: starts = set()
    # [file]: a describing line in the first comment block (the generator line alone is not one)
    top = []
    for l in L:
        if l.startswith(';'): top.append(l)
        elif l.strip(): break
    if not any(t.strip(';').strip() and 'generated by' not in t for t in top):
        out.append((1, 'file', 'no file header saying what the file holds'))
    in_header = False
    for n, l in enumerate(L, 1):
        code, cm = split(l)
        if l.startswith(RULE):
            in_header = not in_header
        if cm is None:
            continue
        body = cm.lstrip(';')
        name_line = in_header and L[n - 2].startswith(RULE) and n >= 2
        if len(l.expandtabs(8)) > WIDTH and not DATA_OP.match(code.strip()) and 'insn:' not in cm:
            out.append((n, 'width', 'line is %d columns wide (max %d)' % (len(l.expandtabs(8)), WIDTH)))
        if code.strip() and not LABEL.match(l) and not code.lstrip().startswith("%"):
            w = len(code.rstrip().expandtabs(8)); pos = len(code.expandtabs(8))
            if not ((w < COL and pos == COL) or (w >= COL and pos == w + 1)):
                out.append((n, 'column', 'comment at column %d (expected %d)' % (pos, COL)))
        m = IDA.search(body)
        if m and not l.startswith(RULE):
            out.append((n, 'ida', 'IDA name %s in a comment' % m.group(0)))
        if not name_line and not 'insn:' in cm:
            m = LINEAGE.search(body)
            if m and not re.search(OWN + r' ?PC|NHL ?' + OWN, m.group(0), re.I): out.append((n, 'lineage', 'other game named in a comment: %s' % m.group(0)))
    # [para]: header and block comments (lines that are only a comment)
    i = 0
    while i < len(L):
        if L[i].startswith(';') and not L[i].startswith(RULE) and i > 0:
            j = i
            while j < len(L) and L[j].startswith(';') and not L[j].startswith(RULE): j += 1
            para = start = 0
            for k in range(i, j + 1):
                if k == j or re.match(r'^;\s*$', L[k]):
                    if para > MAXPARA: out.append((start + 1, 'para', 'comment paragraph of %d lines (max %d)' % (para, MAXPARA)))
                    para = 0
                else:
                    if para == 0: start = k
                    para += 1
            i = j
        i += 1
    # [header]
    for k in sorted(starts):
        name = L[k].split(':')[0]
        c = k
        while c > 0 and (L[c - 1].startswith((';', '%')) and not L[c - 1].startswith(RULE)): c -= 1
        if not (c > 0 and L[c - 1].startswith(RULE)):
            out.append((k + 1, 'header', 'routine %s has no header' % name)); continue
        b = c - 2
        while b > 0 and not L[b].startswith(RULE): b -= 1
        if c - 1 - b < 3:
            out.append((k + 1, 'header', 'header of %s has no description' % name))
    # [data]: a label followed by data (not code), and not a routine start
    for k, l in enumerate(L):
        m = LABEL.match(l)
        if not m or k in starts: continue
        nxt = None
        for j in range(k + 1, min(k + 40, len(L))):
            s = L[j].strip()
            if not s or s.startswith((';', '%')) or LABEL.match(s): continue
            nxt = s; break
        if nxt is None or not DATA_OP.match(nxt): continue
        if split(l)[1] is None:
            out.append((k + 1, 'data', 'data label %s has no comment' % m.group(1)))
    return out


def files(args):
    if args: return args
    return sorted(f for f in glob.glob(os.path.join(asmaddr.SRC, '**', '*.asm'), recursive=True) if os.path.isfile(f))


def main(argv):
    summary = '--summary' in argv
    only = None
    if '--rule' in argv:
        only = set(argv[argv.index('--rule') + 1].split(','))
        del argv[argv.index('--rule'):argv.index('--rule') + 2]
    paths = files([a for a in argv if not a.startswith('--')])
    count = {}; total = 0
    for p in paths:
        top = os.path.relpath(p, asmaddr.SRC).split(os.sep)
        top = '/'.join(top[:2]) if top[0] in ('data', 'lib') and len(top) > 2 else top[0]
        for n, r, msg in check(p):
            if only and r not in only: continue
            total += 1
            count.setdefault(r, {}).setdefault(top, 0); count[r][top] += 1
            if not summary:
                try: print('%s:%d: [%s] %s' % (os.path.relpath(p), n, r, msg))
                except BrokenPipeError: return 1
    if summary:
        for r in RULES:
            if r in count:
                print('%-8s %6d  %s' % (r, sum(count[r].values()),
                                        ', '.join('%s %d' % kv for kv in sorted(count[r].items(), key=lambda x: -x[1]))))
    print('%d comment problem(s)' % total if total else 'comments OK')
    return 1 if total else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
